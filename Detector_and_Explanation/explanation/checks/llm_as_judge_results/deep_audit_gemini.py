ROOT = os.path.join(EXPLAIN_DIR, "rag_kg_ablation", "self_consistency_20x5")
OUT_DIR = os.path.join(EXPLAIN_DIR, "rag_kg_ablation", "faithfulness_audit_gemini31pro")
os.makedirs(OUT_DIR, exist_ok=True)
FILES = sorted(d for d in os.listdir(ROOT) if os.path.isdir(os.path.join(ROOT, d)))

corpus = json.load(open(os.path.join(EXPLAIN_DIR, "rfc_corpus.json"), encoding="utf-8"))
corpus_by_citation = {e["citation"]: e["text"] for e in corpus}

MODEL = "gemini-3.1-flash-lite"
RATE_LIMIT_SLEEP_SECONDS = 13
RETRY_MAX = 3
RETRY_BACKOFF_SECONDS = 20

SYSTEM_PROMPT = (
    "An automated pipeline detects EVPN/BGP faults from packet captures and "
    "generates an explanation for each one. Part of that explanation is a "
    "passage of RFC-grounded reasoning, citing specific RFC text to justify "
    "why the detected condition is a fault.\n\n"
    "The explanation is expected to combine the RFC's general rule with "
    "specific facts about the detected incident, such as node names, "
    "timestamps, and the observed event. That combination is correct and "
    "expected. Do not flag a sentence merely for stating an incident-specific "
    "fact that the RFC text itself does not mention, that fact comes from the "
    "detector, not from the RFC, and citing the RFC to explain why that fact "
    "matters is exactly what this passage is supposed to do.\n\n"
    "Only flag a place where the passage's own claim about what the RFC "
    "itself says has changed in meaning from the real RFC text, an inversion, "
    "a contradiction, a wrong definition, a term substituted for a different "
    "term, or a rule's scope broadened or narrowed in a way that changes what "
    "the rule actually requires or permits.\n\n"
    "For each such place, classify it as one of two types:\n"
    "MEANING_CHANGE: the passage asserts something about the RFC that "
    "directly contradicts, inverts, or is materially wrong about what the RFC "
    "text says.\n"
    "PRECISION_GAP: the passage's claim about the RFC is still directionally "
    "correct, but drops or softens a real qualifier, condition, or exact term "
    "in a way that is imprecise rather than wrong.\n\n"
    "Do not flag phrasing, style, or word choice differences that do not "
    "change what is being claimed about the RFC. Do not flag a sentence for "
    "combining RFC content with incident-specific facts.\n\n"
    "For each issue found, answer in exactly this format:\n"
    "ISSUE <n>:\n"
    "TYPE: MEANING_CHANGE or PRECISION_GAP\n"
    "EXPECTED: <what the real RFC text actually says>\n"
    "FOUND: <what the passage actually claims about the RFC>\n"
    "LOCATION: <the specific sentence or phrase>\n"
    "REASON: <why this changes or softens the RFC's actual meaning>\n\n"
    "If no issues are found, respond with:\n"
    "NO ISSUES FOUND"
)


def build_user_prompt(grounding_text, citations):
    passages_block = []
    for c in citations:
        text = corpus_by_citation.get(c, "[PASSAGE NOT FOUND]")
        passages_block.append(f"=== {c} ===\n{text}")
    passages_joined = "\n\n".join(passages_block)
    return (
        f"RFC-GROUNDED REASONING PASSAGE (generated by the pipeline):\n{grounding_text}\n\n"
        f"ACTUAL RFC TEXT IT WAS GROUNDED IN (all cited passages, full text):\n{passages_joined}"
    )


def parse_issues(raw_text):
    if raw_text is None:
        return None
    if "NO ISSUES FOUND" in raw_text.upper() and "ISSUE 1:" not in raw_text.upper():
        return []
    issues = []
    blocks = re.split(r"\nISSUE\s+\d+:", "\n" + raw_text)
    for block in blocks[1:]:
        def grab(field):
            m = re.search(rf"{field}:\s*(.*?)(?=\n[A-Z]+:|\Z)", block, re.DOTALL)
            return m.group(1).strip() if m else None
        issues.append({
            "type": grab("TYPE"),
            "expected": grab("EXPECTED"),
            "found": grab("FOUND"),
            "location": grab("LOCATION"),
            "reason": grab("REASON"),
        })
    return issues


examples = []
for fstem in FILES:
    d = json.load(open(os.path.join(ROOT, fstem, "run_1.json"), encoding="utf-8"))
    sections = dict(parse_sections(d["explanation"]))
    grounding = sections.get("RFC GROUNDING", "")
    grounding = re.split(r"\nCONFIDENCE:", grounding)[0].strip()
    citations = d["citations"]
    user_prompt = build_user_prompt(grounding, citations)
    examples.append({"file": fstem, "user_prompt": user_prompt})

LIMIT = int(os.environ.get("DEEP_AUDIT_GEMINI_LIMIT", "0")) or None
if LIMIT:
    examples = examples[:LIMIT]

print(f"Total calls: {len(examples)}")

client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])

run_start = time.time()
records = []
for i, ex in enumerate(examples, 1):
    out_path = os.path.join(OUT_DIR, f"{ex['file']}.json")
    time.sleep(RATE_LIMIT_SLEEP_SECONDS)
    t0 = time.time()
    attempt = 0
    raw = None
    usage = None
    model_returned = None
    status = "OK"
    error = None
    while True:
        try:
            response = client.models.generate_content(
                model=MODEL,
                contents=ex["user_prompt"],
                config=types.GenerateContentConfig(system_instruction=SYSTEM_PROMPT),
            )
            raw = response.text
            model_returned = getattr(response, "model_version", None) or MODEL
            u = getattr(response, "usage_metadata", None)
            usage = {
                "prompt_token_count": getattr(u, "prompt_token_count", None) if u else None,
                "candidates_token_count": getattr(u, "candidates_token_count", None) if u else None,
                "total_token_count": getattr(u, "total_token_count", None) if u else None,
            }
            break
        except Exception as e:
            is_503 = "503" in str(e) or "UNAVAILABLE" in str(e)
            attempt += 1
            if is_503 and attempt <= RETRY_MAX:
                print(f"  503, retry {attempt}/{RETRY_MAX} after {RETRY_BACKOFF_SECONDS}s: {ex['file']}")
                time.sleep(RETRY_BACKOFF_SECONDS)
                continue
            status = "FAILED"
            error = f"{type(e).__name__}: {e}"
            break
    elapsed = time.time() - t0

    rec = {
        "file": ex["file"],
        "judge_model": MODEL,
        "model_returned": model_returned,
        "raw_response": raw,
        "parsed_issues": parse_issues(raw),
        "status": status,
        "error": error,
        "elapsed_seconds": elapsed,
        "usage": usage,
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
    }
    records.append(rec)

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(rec, f, indent=1, default=str)

    n_issues = len(rec["parsed_issues"]) if rec["parsed_issues"] is not None else "PARSE_FAIL"
    print(f"[{i}/{len(examples)}] {ex['file']}: status={status} n_issues={n_issues} saved={out_path} ({elapsed:.1f}s)")

run_elapsed = time.time() - run_start

summary_path = os.path.join(
    r"C:\Users\KSJAYA~1\AppData\Local\Temp\claude\C--simulation-pcap\2728fa27-f217-4791-81ce-27424551174a\scratchpad",
    "deep_audit_gemini_summary.json",
)
with open(summary_path, "w", encoding="utf-8") as f:
    json.dump({
        "total_wall_clock_seconds": run_elapsed,
        "n_calls": len(examples),
        "n_ok": sum(1 for r in records if r["status"] == "OK"),
        "n_failed": sum(1 for r in records if r["status"] == "FAILED"),
        "model": MODEL,
        "concurrent": False,
        "rate_limit_sleep_seconds": RATE_LIMIT_SLEEP_SECONDS,
        "records": records,
    }, f, indent=1, default=str)

